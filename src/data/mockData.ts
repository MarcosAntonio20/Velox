/** Arredonda a média de avaliações para uma casa decimal. */
const calculateAverageRating = (productReviews: Review[]): number => {
  if (productReviews.length === 0) {
    return 0;
  }

  const sum = productReviews.reduce((accumulator, review) => accumulator + review.rating, 0);
  return Math.round((sum / productReviews.length) * 10) / 10;
};

export const products: Product[] = productsBase.map((product) => {
  const productReviews = reviews.filter((review) => review.productId === product.id);

  return {
    ...product,
    rating: calculateAverageRating(productReviews),
    reviewCount: productReviews.length,
  };
});

